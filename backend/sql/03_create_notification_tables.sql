-- SignalMesh AI — Notification System Tables
-- Stores user subscriptions and notification history
-- Team: Apex-AI-X

USE DATABASE SIGNALMESH_AI;
USE SCHEMA DISASTER_RISK;

-- User Notification Subscriptions
CREATE TABLE IF NOT EXISTS USER_SUBSCRIPTIONS (
    SUBSCRIPTION_ID VARCHAR(50) PRIMARY KEY,
    USER_ID VARCHAR(100) NOT NULL, -- From auth system or browser fingerprint
    FCM_TOKEN VARCHAR(500) NOT NULL, -- Firebase Cloud Messaging token
    TOKEN_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', -- 'ACTIVE', 'EXPIRED', 'INVALID'
    
    -- Subscription Preferences
    DISTRICT_IDS VARIANT, -- JSON array of district IDs to monitor
    STATE_NAMES VARIANT, -- JSON array of state names to monitor
    RISK_THRESHOLD VARCHAR(20) NOT NULL DEFAULT 'HIGH', -- 'MODERATE', 'HIGH', 'VERY_HIGH', 'EXTREME'
    
    -- Notification Settings
    ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    DEMO_ALERTS_ENABLED BOOLEAN NOT NULL DEFAULT FALSE,
    COOLDOWN_MINUTES NUMBER(10,0) NOT NULL DEFAULT 60,
    
    -- Metadata
    DEVICE_INFO VARCHAR(500),
    LAST_NOTIFIED_AT TIMESTAMP_NTZ,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- Notification History
CREATE TABLE IF NOT EXISTS NOTIFICATION_HISTORY (
    NOTIFICATION_ID VARCHAR(50) PRIMARY KEY,
    SUBSCRIPTION_ID VARCHAR(50) NOT NULL,
    USER_ID VARCHAR(100) NOT NULL,
    
    -- Alert Information
    DISTRICT_ID NUMBER(10,0) NOT NULL,
    STATE_NAME VARCHAR(100) NOT NULL,
    DISTRICT_NAME VARCHAR(100) NOT NULL,
    RISK_LEVEL VARCHAR(20) NOT NULL,
    RISK_SCORE NUMBER(10,2) NOT NULL,
    
    -- Trigger Information
    TRIGGER_REASON VARCHAR(200) NOT NULL,
    ASSESSMENT_ID VARCHAR(50), -- Link to LIVE_RISK_HISTORY
    ASSESSMENT_TYPE VARCHAR(20) NOT NULL, -- 'LIVE', 'DEMO', 'TEST'
    
    -- Delivery Status
    DELIVERY_STATUS VARCHAR(20) NOT NULL, -- 'SENT', 'DELIVERED', 'FAILED', 'CLICKED'
    DELIVERY_TIMESTAMP TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    FCM_RESPONSE VARIANT, -- Firebase response details
    ERROR_MESSAGE VARCHAR(500),
    
    -- Engagement
    CLICKED_AT TIMESTAMP_NTZ,
    
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- Indexes
CREATE INDEX IF NOT EXISTS IDX_SUBSCRIPTIONS_USER 
    ON USER_SUBSCRIPTIONS(USER_ID);

CREATE INDEX IF NOT EXISTS IDX_SUBSCRIPTIONS_TOKEN_STATUS 
    ON USER_SUBSCRIPTIONS(TOKEN_STATUS, ENABLED);

CREATE INDEX IF NOT EXISTS IDX_NOTIFICATIONS_SUBSCRIPTION 
    ON NOTIFICATION_HISTORY(SUBSCRIPTION_ID, CREATED_AT DESC);

CREATE INDEX IF NOT EXISTS IDX_NOTIFICATIONS_USER 
    ON NOTIFICATION_HISTORY(USER_ID, CREATED_AT DESC);

CREATE INDEX IF NOT EXISTS IDX_NOTIFICATIONS_DISTRICT 
    ON NOTIFICATION_HISTORY(DISTRICT_ID, CREATED_AT DESC);

-- Comments
COMMENT ON TABLE USER_SUBSCRIPTIONS IS 'User alert subscriptions with FCM tokens and preferences';
COMMENT ON TABLE NOTIFICATION_HISTORY IS 'Complete history of sent notifications with delivery tracking';

SELECT 'Notification tables created successfully' AS status;
