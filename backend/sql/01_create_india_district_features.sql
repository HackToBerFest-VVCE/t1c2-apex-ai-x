-- Verification queries
SELECT 'Total Districts' AS metric, COUNT(*) AS value FROM INDIA_DISTRICT_FEATURES
UNION ALL
SELECT 'Total States', COUNT(DISTINCT STATE_NAME) FROM INDIA_DISTRICT_FEATURES
UNION ALL
SELECT 'LOW Risk', COUNT(*) FROM INDIA_DISTRICT_FEATURES WHERE RISK_LEVEL = 'LOW'
UNION ALL
SELECT 'MODERATE Risk', COUNT(*) FROM INDIA_DISTRICT_FEATURES WHERE RISK_LEVEL = 'MODERATE'
UNION ALL
SELECT 'HIGH Risk', COUNT(*) FROM INDIA_DISTRICT_FEATURES WHERE RISK_LEVEL = 'HIGH'
UNION ALL
SELECT 'VERY_HIGH Risk', COUNT(*) FROM INDIA_DISTRICT_FEATURES WHERE RISK_LEVEL = 'VERY_HIGH'
UNION ALL
SELECT 'EXTREME Risk', COUNT(*) FROM INDIA_DISTRICT_FEATURES WHERE RISK_LEVEL = 'EXTREME';

-- Show state coverage
SELECT STATE_NAME, COUNT(*) AS district_count
FROM INDIA_DISTRICT_FEATURES
GROUP BY STATE_NAME
ORDER BY STATE_NAME;

-- Show sample districts
SELECT STATE_NAME, DISTRICT_NAME, RISK_LEVEL, RISK_SCORE, DATA_SOURCE
FROM INDIA_DISTRICT_FEATURES
ORDER BY RISK_SCORE DESC
LIMIT 10;
