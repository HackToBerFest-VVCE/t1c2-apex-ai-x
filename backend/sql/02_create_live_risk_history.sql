-- SignalMesh AI — Live Risk History Table
-- Stores historical snapshots of live risk assessments for trending analysis
-- Team: Apex-AI-X

USE DATABASE SIGNALMESH_AI;
USE SCHEMA DISASTER_RISK;

-- Create LIVE_RISK_HISTORY table
CREATE TABLE IF NOT EXISTS LIVE_RISK_HISTORY (
    ASSESSMENT_ID VARCHAR(50) PRIMARY KEY,
    DISTRICT_ID NUMBER(10,0) NOT NULL,
    STATE_NAME VARCHAR(100) NOT NULL,
    DISTRICT_NAME VARCHAR(100) NOT NULL,
    
    -- Assessment Results
    RISK_SCORE NUMBER(10,2) NOT NULL,
    RISK_LEVEL VARCHAR(20) NOT NULL,
    PREVIOUS_RISK_LEVEL VARCHAR(20),
    RISK_CHANGE VARCHAR(20), -- 'INCREASED', 'DECREASED', 'STABLE'
    
    -- Environmental Measurements (Available Data)
    RAINFALL_MM NUMBER(10,2),
    RAINFALL_SOURCE VARCHAR(100),
    RAINFALL_TIMESTAMP TIMESTAMP_NTZ,
    
    FORECAST_RAINFALL_MM NUMBER(10,2),
    FORECAST_SOURCE VARCHAR(100),
    FORECAST_TIMESTAMP TIMESTAMP_NTZ,
    
    TERRAIN_SLOPE_FACTOR NUMBER(10,2),
    SOIL_STABILITY_INDEX NUMBER(10,2),
    SEISMIC_ACTIVITY_LEVEL NUMBER(10,2),
    VEGETATION_COVER NUMBER(10,2),
    
    -- Data Quality & Metadata
    DATA_FRESHNESS VARCHAR(20), -- 'LIVE', 'RECENT', 'STALE', 'UNAVAILABLE'
    DATA_SOURCES_USED VARIANT, -- JSON array of sources actually used
    MISSING_INPUTS VARIANT, -- JSON array of unavailable inputs
    CONFIDENCE_SCORE NUMBER(5,2), -- 0-100 based on data availability
    
    -- Assessment Metadata
    ASSESSMENT_VERSION VARCHAR(20) NOT NULL DEFAULT '1.0',
    ASSESSMENT_TYPE VARCHAR(20) NOT NULL, -- 'LIVE', 'DEMO', 'SCHEDULED'
    
    -- Contributing Factors
    TOP_FACTOR_1 VARCHAR(100),
    TOP_FACTOR_1_CONTRIBUTION NUMBER(5,2),
    TOP_FACTOR_2 VARCHAR(100),
    TOP_FACTOR_2_CONTRIBUTION NUMBER(5,2),
    TOP_FACTOR_3 VARCHAR(100),
    TOP_FACTOR_3_CONTRIBUTION NUMBER(5,2),
    
    -- Timestamps
    OBSERVATION_TIMESTAMP TIMESTAMP_NTZ, -- When data was observed
    RETRIEVAL_TIMESTAMP TIMESTAMP_NTZ NOT NULL, -- When we retrieved it
    ASSESSMENT_TIMESTAMP TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(), -- When assessment was made
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- Create indexes for efficient querying
CREATE INDEX IF NOT EXISTS IDX_LIVE_HISTORY_DISTRICT 
    ON LIVE_RISK_HISTORY(DISTRICT_ID, ASSESSMENT_TIMESTAMP DESC);

CREATE INDEX IF NOT EXISTS IDX_LIVE_HISTORY_STATE 
    ON LIVE_RISK_HISTORY(STATE_NAME, ASSESSMENT_TIMESTAMP DESC);

CREATE INDEX IF NOT EXISTS IDX_LIVE_HISTORY_TIMESTAMP 
    ON LIVE_RISK_HISTORY(ASSESSMENT_TIMESTAMP DESC);

-- Comments
COMMENT ON TABLE LIVE_RISK_HISTORY IS 'Historical snapshots of live risk assessments with data quality tracking';
COMMENT ON COLUMN LIVE_RISK_HISTORY.DATA_FRESHNESS IS 'LIVE (<1h), RECENT (1-24h), STALE (>24h), UNAVAILABLE';
COMMENT ON COLUMN LIVE_RISK_HISTORY.ASSESSMENT_TYPE IS 'LIVE (real data), DEMO (synthetic), SCHEDULED (automated)';
COMMENT ON COLUMN LIVE_RISK_HISTORY.CONFIDENCE_SCORE IS '0-100 based on data availability and freshness';

SELECT 'LIVE_RISK_HISTORY table created successfully' AS status;
