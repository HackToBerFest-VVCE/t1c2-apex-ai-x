-- SignalMesh AI — Alert History Table
-- Stores triggered emergency alerts

USE DATABASE SIGNALMESH_AI;
USE SCHEMA DISASTER_RISK;

CREATE TABLE IF NOT EXISTS ALERT_HISTORY (
    ALERT_ID VARCHAR(100) PRIMARY KEY,
    LOCATION VARCHAR(200) NOT NULL,
    COORDINATES VARIANT, -- JSON: {lat, lng}
    RISK_SCORE NUMBER(5,2) NOT NULL,
    RISK_LEVEL VARCHAR(20) NOT NULL, -- LOW, MODERATE, HIGH, CRITICAL, EXTREME
    TRIGGER_FACTORS VARIANT, -- JSON array
    DISTRICT_ID NUMBER(10,0),
    EVACUATION_DIRECTION VARCHAR(1000),
    RECIPIENT_PHONE VARCHAR(50),
    STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE, ACKNOWLEDGED, RESOLVED
    ACKNOWLEDGED_AT TIMESTAMP_NTZ,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE INDEX IF NOT EXISTS IDX_ALERT_HISTORY_CREATED ON ALERT_HISTORY(CREATED_AT);
CREATE INDEX IF NOT EXISTS IDX_ALERT_HISTORY_LEVEL ON ALERT_HISTORY(RISK_LEVEL, CREATED_AT);
CREATE INDEX IF NOT EXISTS IDX_ALERT_HISTORY_DISTRICT ON ALERT_HISTORY(DISTRICT_ID, CREATED_AT);

COMMENT ON TABLE ALERT_HISTORY IS 'Emergency alert history triggered by AI/ML model predictions';

SELECT 'ALERT_HISTORY table created successfully' AS status;
