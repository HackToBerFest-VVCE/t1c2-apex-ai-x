/**
 * DataDisclaimer — Important notice about data sources
 * Ensures users understand distinction between demo district data and live nation data
 */

import { Info, AlertTriangle } from "lucide-react";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import DataSourceBadge from "@/components/DataSourceBadge";

export default function DataDisclaimer({ variant = "info", className = "" }) {
  if (variant === "district-demo") {
    return (
      <Alert className={`bg-amber-500/10 border-amber-500/30 ${className}`}>
        <AlertTriangle className="h-4 w-4 text-amber-400" />
        <AlertTitle className="text-amber-200 font-semibold">District Data Notice</AlertTitle>
        <AlertDescription className="text-sm text-amber-100/90 mt-2">
          <div className="flex items-center gap-2 mb-2">
            <DataSourceBadge source="demo" />
            <span className="text-xs">Northeast India district monitoring</span>
          </div>
          <p className="leading-relaxed">
            District-level risk scores, environmental factors, and alerts shown are 
            <strong> demonstration data</strong> for prototype purposes. These values are 
            synthetic and do not represent actual real-world measurements or predictions.
          </p>
          <p className="mt-2 text-xs text-amber-200">
            For actual disaster preparedness, consult official government agencies and meteorological departments.
          </p>
        </AlertDescription>
      </Alert>
    );
  }

  if (variant === "nation-live") {
    return (
      <Alert className={`bg-emerald-500/10 border-emerald-500/30 ${className}`}>
        <Info className="h-4 w-4 text-emerald-400" />
        <AlertTitle className="text-emerald-200 font-semibold">Live Nation-Level Data</AlertTitle>
        <AlertDescription className="text-sm text-emerald-100/90 mt-2">
          <div className="flex items-center gap-2 mb-2">
            <DataSourceBadge source="live" />
            <span className="text-xs">Connected to Snowflake database</span>
          </div>
          <p className="leading-relaxed">
            Nation-level risk assessments are retrieved from the SIGNALMESH_AI.DISASTER_RISK 
            schema in Snowflake. Environmental features are synthetic demonstration data 
            processed through ML models.
          </p>
          <p className="mt-2 text-xs text-emerald-200">
            Note: Risk scores are generated by uncalibrated ML models for hackathon demonstration.
          </p>
        </AlertDescription>
      </Alert>
    );
  }

  // Generic info variant
  return (
    <Alert className={`bg-blue-500/10 border-blue-500/30 ${className}`}>
      <Info className="h-4 w-4 text-blue-400" />
      <AlertDescription className="text-sm text-blue-100/90">
        <p className="leading-relaxed">
          <strong>SignalMesh AI</strong> integrates ML-powered risk assessment with Snowflake 
          data infrastructure. District-level monitoring uses demonstration data, while 
          nation-level assessments connect to live database.
        </p>
      </AlertDescription>
    </Alert>
  );
}

/**
 * Compact inline disclaimer
 */
export function InlineDisclaimer({ children }) {
  return (
    <div className="flex items-start gap-2 text-xs text-slate-400 bg-slate-800/30 rounded-lg px-3 py-2 border border-slate-700/50">
      <Info className="h-3.5 w-3.5 mt-0.5 shrink-0" />
      <span className="leading-relaxed">{children}</span>
    </div>
  );
}
